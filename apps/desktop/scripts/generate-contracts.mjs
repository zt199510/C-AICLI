import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(desktopRoot, "../..");
const contractPath = path.join(repoRoot, "protocol", "desktop-v1", "contract.json");
const csharpPath = path.join(
  repoRoot,
  "src",
  "CSharpAiCli.AppHost",
  "Protocol",
  "Generated",
  "DesktopProtocolContracts.g.cs",
);
const typescriptPath = path.join(desktopRoot, "src", "generated", "desktop-contracts.ts");
const checkOnly = process.argv.includes("--check");
const contract = JSON.parse(await readFile(contractPath, "utf8"));

const pascal = (value) => value.charAt(0).toUpperCase() + value.slice(1);

function csharpType(type) {
  if (type === "string") return "string";
  if (type === "string?") return "string?";
  if (type === "boolean") return "bool";
  if (type === "string[]") return "IReadOnlyList<string>";
  return type;
}

function typescriptType(type) {
  if (type === "string") return "string";
  if (type === "string?") return "string | null";
  if (type === "boolean") return "boolean";
  if (type === "string[]") return "string[]";
  return type;
}

function renderCsharp() {
  const lines = [
    "// <auto-generated />",
    "#nullable enable",
    "using System.Text.Json.Serialization;",
    "",
    "namespace CSharpAiCli.AppHost.Protocol.Generated;",
    "",
    "public static class DesktopProtocolDefinition",
    "{",
    `    public const string Version = ${JSON.stringify(contract.protocolVersion)};`,
    `    public const int MaxHeaderBytes = ${contract.limits.maxHeaderBytes};`,
    `    public const int MaxBodyBytes = ${contract.limits.maxBodyBytes};`,
    `    public const int MaxDiagnosticBytes = ${contract.limits.maxDiagnosticBytes};`,
  ];
  for (const method of contract.methods) {
    lines.push(`    public const string ${method.constant} = ${JSON.stringify(method.name)};`);
  }
  lines.push("}", "");

  for (const type of contract.types) {
    lines.push(`public sealed record ${type.name}(`);
    type.properties.forEach((property, index) => {
      const suffix = index === type.properties.length - 1 ? ");" : ",";
      lines.push(
        `    [property: JsonPropertyName(${JSON.stringify(property.jsonName)})] ${csharpType(property.type)} ${pascal(property.jsonName)}${suffix}`,
      );
    });
    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

function renderTypescript() {
  const lines = [
    "// <auto-generated />",
    `export const PROTOCOL_VERSION = ${JSON.stringify(contract.protocolVersion)} as const;`,
    "export const PROTOCOL_LIMITS = Object.freeze({",
    `  maxHeaderBytes: ${contract.limits.maxHeaderBytes},`,
    `  maxBodyBytes: ${contract.limits.maxBodyBytes},`,
    `  maxDiagnosticBytes: ${contract.limits.maxDiagnosticBytes},`,
    "});",
    "export const DESKTOP_METHODS = Object.freeze({",
  ];
  for (const method of contract.methods) {
    lines.push(`  ${method.constant}: ${JSON.stringify(method.name)},`);
  }
  lines.push("});", "");

  for (const type of contract.types) {
    lines.push(`export interface ${type.name} {`);
    for (const property of type.properties) {
      lines.push(`  ${property.jsonName}: ${typescriptType(property.type)};`);
    }
    lines.push("}", "");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

async function emit(filePath, expected) {
  if (checkOnly) {
    const actual = await readFile(filePath, "utf8").catch(() => "");
    if (actual !== expected) {
      throw new Error(`Generated contract is stale: ${path.relative(repoRoot, filePath)}`);
    }
    return;
  }

  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, expected, "utf8");
}

await emit(csharpPath, renderCsharp());
await emit(typescriptPath, renderTypescript());
